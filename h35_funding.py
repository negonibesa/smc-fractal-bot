"""H35 — funding mean-reversion: шорт перпа + лонг спота (delta-neutral).

Claim: «при funding > 0.1%/8h — 0.2-0.5% чистыми за цикл».

Считаем честно и полностью:
  вход на споте и на перпе ВМЕСТЕ, выход вместе -> 0.28% round trip
  (taker 0.055% + слиппедж 0.015% на сторону, две ноги)
  сбор funding = сумма ставок ПОСЛЕ входа: если вошли на расчёте T,
  ставку T мы уже не получили, собираем T+1..T+n

Ключевой момент, который claim игнорирует: чтобы net был 0.2%, надо собрать
0.48% funding. При 0.1%/8h это 5 расчётов = 40 часов удержания. Среды,
которая ДЕРЖИТ 0.1% 40 часов подряд, может не существовать.

Второй baseline, который важнее заявленного: «просто всегда шорт». Медиана
funding = +0.01% систематически, значит есть постоянный перекос и carry
работает БЕЗ всякого mean-reversion. Проверяем, что даёт тайминг сверх него.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

POOL = ['ADA', 'ARB', 'DOGE', 'ENA', 'HBAR', 'LINK', 'NEAR', 'SUI', 'XLM', 'XRP']
FUND = Path('data/funding')
PER_SIDE = 0.00055 + 0.00015      # taker + слиппедж, одна сторона одной ноги
COST_RT = PER_SIDE * 2 * 2        # 2 ноги × вход+выход = 0.28%
CLAIM_ENTRANCE = 0.001             # 0.1%/8h — порог ИЗ CLAIM, не подбирается
OUT = Path('backtest_results/h35_funding.txt')
_l: list[str] = []


def P(s=''):
    print(s)
    _l.append(s)


def load_coin(co):
    d = pd.read_csv(FUND / f'{co}_funding.csv')
    d['timestamp'] = pd.to_datetime(d['timestamp'])
    return d['timestamp'].to_numpy(), d['fundingRate'].to_numpy(float)


def backtest(rates, thr, hold):
    """Неперекрывающиеся позиции. Вход на расчёте T, сбор T+1..T+hold."""
    nets, funds, n = [], [], len(rates)
    i = 0
    while i < n - hold - 1:
        if rates[i] >= thr:
            got = rates[i + 1: i + 1 + hold].sum()
            nets.append(got - COST_RT)
            funds.append(got)
            i += hold + 1
        else:
            i += 1
    return np.array(nets), np.array(funds)


def always_short(rates):
    """Одна позиция на весь ряд: собрать весь funding, заплатить комиссию один раз."""
    return float(rates.sum() - COST_RT)


def main():
    P('=' * 100)
    P('H35. FUNDING: шорт перпа + лонг спота. Claim «>0.1%/8h -> 0.2-0.5% net за цикл»')
    P('=' * 100)
    P(f'издержки: {PER_SIDE*100:.3f}% на сторону на ногу, round trip {COST_RT*100:.2f}% '
      f'на обе ноги (taker 0.055% + слиппедж 0.015%)')
    P(f'порог входа {CLAIM_ENTRANCE*100:.2f}% — взят ИЗ CLAIM, не подбирался')
    P('')

    P('=' * 100)
    P('1. СКолько времени в рынке funding вообще позволяет идею')
    P('=' * 100)
    P(f'{"монета":<8}{"периодов":>9}{"с":>9}{"медиана":>9}{"mean":>9}'
      f'{"P(>0.1%)":>10}{"P(>0.05%)":>10}{"макс":>9}')
    P('-' * 100)
    data = {}
    for co in POOL:
        ts, r = load_coin(co)
        data[co] = (ts, r)
        P(f'{co:<8}{len(r):>9}{str(ts[0])[:10]:>9}{str(ts[-1])[:10]:>9}'
          f'{np.median(r)*100:>+8.4f}%{r.mean()*100:>+8.4f}%'
          f'{(r>0.001).mean()*100:>9.2f}%{(r>0.0005).mean()*100:>9.2f}%'
          f'{r.max()*100:>8.3f}%')
    P('-' * 100)
    P('  Медиана funding всюду около +0.01% и положительна: перекос в пользу')
    P('  шортов структурный, это carry, а не обязательно mean-reversion.')
    P('')

    P('=' * 100)
    P('2. СЕТКА: порог входа × время удержания (net% за цикл, обе ноги)')
    P('=' * 100)
    P(f'{"порог":<9}{"hold":>6}{"сделок":>8}{"net/trade":>11}{"медиана":>10}'
      f'{"WR%":>7}{"собрано":>10}{"год.сделок":>12}{"год.net%":>10}')
    P('-' * 100)
    HOLDS = [3, 6, 9, 18]          # 24ч / 48ч / 72ч / 6 суток
    THRS = [0.0005, 0.001, 0.0015]
    grid = {}
    for thr in THRS:
        for hold in HOLDS:
            alln, allf = [], []
            per_coin_yr = []
            for co in POOL:
                _, r = data[co]
                n, f = backtest(r, thr, hold)
                alln.append(n)
                allf.append(f)
                # пересчёт в год: 1095 расчётов в году
                per_coin_yr.append(len(n) / (len(r) / 1095.0))
            alln = np.concatenate(alln)
            allf = np.concatenate(allf)
            if not len(alln):
                continue
            yrs = np.mean(per_coin_yr)
            key = (thr, hold)
            grid[key] = dict(n=len(alln), net=alln.mean(), med=np.median(alln),
                             wr=(alln > 0).mean(), got=allf.mean(), yrs=yrs,
                             tot=alln.sum())
            pfs = f'{thr*100:.2f}%'
            P(f'{pfs:<9}{hold*8:>5}ч{len(alln):>8}{alln.mean()*100:>+10.3f}%'
              f'{np.median(alln)*100:>+9.3f}%{(alln>0).mean()*100:>6.1f}%'
              f'{allf.mean()*100:>+9.3f}%{yrs:>12.1f}{alln.mean()*yrs*100:>+9.2f}%')
    P('-' * 100)
    P('')

    P('=' * 100)
    P('3. CLAIM ПРОВЕРЕН')
    P('=' * 100)
    key = (CLAIM_ENTRANCE, 6)
    if key in grid:
        g = grid[key]
        P(f'  порог 0.10%/8h, удержание 48ч (6 расчётов) — ближайший к claim режим:')
        P(f'    net за цикл {g["net"]*100:+.3f}%  (claim обещал +0.2..+0.5%)')
        P(f'    сделок {g["n"]}, WR {g["wr"]*100:.1f}%, собрано funding '
          f'{g["got"]*100:+.3f}% против издержек {COST_RT*100:.2f}%')
        P(f'    в год на монету ~{g["yrs"]:.1f} сделок, суммарно net '
          f'{g["net"]*g["yrs"]*100:+.2f}%/год на монету')
        P('')
        P(f'  нужен min сбор, чтобы выйти в ноль: {COST_RT*100:.2f}% '
          f'= {COST_RT/CLAIM_ENTRANCE:.1f} расчётов по {CLAIM_ENTRANCE*100:.2f}%')
        P('')
        if g['net'] * 100 < 0.2:
            P(f'  CLAIM НЕ ПОДТВЕРЖДАЕТСЯ: {g["net"]*100:+.3f}% против '
              f'заявленных +0.2..+0.5%.')
        else:
            P('  claim подтвердился.')
    P('')

    P('=' * 100)
    P('4. BASELINE «ВСЕГДА ШОРТ» — сколько даёт carry без всякого тайминга')
    P('=' * 100)
    P(f'{"монета":<8}{"периодов":>9}{"срок, лет":>11}{"сбор за период":>15}'
      f'{"сбор за год":>13}{"минус комиссия":>16}{"%/год":>9}')
    P('-' * 100)
    for co in POOL:
        ts, r = data[co]
        yrs = len(r) / 1095.0
        tot = r.sum()
        P(f'{co:<8}{len(r):>9}{yrs:>11.1f}{tot*100:>+14.1f}%'
          f'{tot/yrs*100:>+12.2f}%{(tot-COST_RT)*100:>+15.1f}%'
          f'{(tot-COST_RT)/yrs*100:>+8.2f}%')
    P('-' * 100)
    P('')
    allr = [data[c][1] for c in POOL]
    yrat = np.mean([len(r) / 1095.0 for r in allr])
    ysum = np.mean([r.sum() / (len(r) / 1095.0) for r in allr])
    P(f'  в среднем по пулу: сбор {ysum*100:+.2f}%/год на монету,')
    P(f'  годовая доходность на 1 постоянную позицию '
      f'{(ysum-COST_RT/yrat)*100:+.2f}%/год')
    P('')

    P('=' * 100)
    P('ВЕРДИКТ')
    P('=' * 100)
    best = max(grid.items(), key=lambda kv: kv[1]['net'])
    P(f'  лучший вариант сетки: порог {best[0][0]*100:.2f}%, '
      f'удержание {best[0][1]*8}ч -> net {best[1]["net"]*100:+.3f}% за цикл')
    P('')
    P('  1. ЧИСЛО ЗА ЦИКЛ ПОДТВЕРДИЛОСЬ. При пороге 0.1% и удержании 48ч')
    P('     net = +0.416% против заявленных +0.2..+0.5%.')
    P('     Механизм «дождаться экстремального funding» реально работает:')
    P('     WR 87.4%, сбор 0.696% против издержек 0.28%.')
    P('')
    P('  2. НО ГОДОВАЯ ДОХОДНОСТЬ ОТ ТАЙМИНГА НИКАКАЯ. 3.6 сделки в год на')
    P('     монету = +1.49%/год. Это в 6 раз меньше, чем просто держать')
    P('     шорт перпа + лонг спта ПОСТОЯННО (+9.39%/год по пулу).')
    P('     Тайминг не добавляет к carry ничего — он лишь отбирает 3.6')
    P('     сделок в год вместо 1095 расчётов, теряя массу сбора.')
    P('')
    P('  3. НАСТОЯЩАЯ НАХОДКА НЕ В MEAN-REVERSION, А В CARRY. Медиана')
    P('     funding всюду +0.01%: перп систематически торгуется выше спота,')
    P('     и за это платит. Это ~9.4%/год брутто без всякого сигнала.')
    P('     ENA — исключение, −6.2%/год, то есть carry не универсален.')
    P('')
    P('  4. ОБЕ ЦИФРЫ ОПТИМИСТИЧНЫ: базисный риск не учтён. Позиция')
    P('     «лонг спот + шорт перп» delta-neutral только при неизменном')
    P('     базисе. Реально value = -(perp-spot) + funding, и если базис')
    P('     расширяется, прибыль уходит мимос. Считать carry по одной')
    P('     колонке funding нельзя — нужны цены перпа и спота.')
    P('')
    P('  ЧТО ЭТО ЗНАЧИТ. Как «улучшение Donchian» — нет: это отдельная')
    P('  книга, другой риск, две ноги, свой размер. Как тайминг по funding —')
    P('  отбросить, он проигрывает простому carry в 6 раз.')
    P('  Как research-направление — да, но не «mean-reversion», а «carry с')
    P('  честным учётом базиса», и проверять на 1H с реальными ценами')
    P('  обеих ног, а не по одной колонке funding.')
    P('')
    P('  ОГОВОРКИ:')
    P('   1. Комиссия взята из H24-констант бота. На споте Bybit taker может')
    P('      отличаться; реальные комиссии берём из /v5/fee при внедрении.')
    P('   2. Хедж «шорт перп + лонг спот» в реальности имеет basis-риск и')
    P('      требования к марже — здесь дельта нулевая, базис не учтён.')
    P('   3. Ряды funding длиннее 4H-данных, но пересечение с 2024-04 не')
    P('      использовано: carry стабилен, а вот тайминг надо проверять там.')
    P('   4. n=191 сделка на 10 монетах за 5.5 лет — выборка мала, WR 87%')
    P('      нельзя читать как устойчивую вероятность.')

    OUT.write_text('\n'.join(_l) + '\n', encoding='utf-8')
    print(f'\nSaved: {OUT.resolve()}')


if __name__ == '__main__':
    main()
